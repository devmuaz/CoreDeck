#!/usr/bin/env python3
"""Pin a Frida release in pins/frida.json.

Usage:
  python3 tools/update_frida_pins.py 17.9.2
"""

import json
import os
import ssl
import sys
import urllib.request
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PINS = ROOT / "pins" / "frida.json"
DEVKITS = (
    "macos-arm64",
    "macos-x86_64",
    "linux-x86_64",
    "linux-arm64",
    "windows-x86_64",
)
SERVERS = (
    "android-arm",
    "android-arm64",
    "android-x86",
    "android-x86_64",
)


def open_release(request: urllib.request.Request):
    paths = ssl.get_default_verify_paths()
    if paths.cafile and os.path.isfile(paths.cafile):
        return urllib.request.urlopen(request)
    system_bundle = "/etc/ssl/cert.pem"
    if os.path.isfile(system_bundle):
        context = ssl.create_default_context(cafile=system_bundle)
        return urllib.request.urlopen(request, context=context)
    return urllib.request.urlopen(request)


def pin_for(assets: dict[str, dict[str, str]], name: str) -> dict[str, str] | None:
    asset = assets.get(name)
    if asset is None:
        return None
    digest = asset.get("digest", "")
    url = asset.get("url", "")
    if not digest.startswith("sha256:") or not url.startswith("https://"):
        return None
    value = digest.removeprefix("sha256:")
    if len(value) != 64 or any(ch not in "0123456789abcdef" for ch in value):
        return None
    return {"url": url, "sha256": value}


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: update_frida_pins.py <version>", file=sys.stderr)
        return 2
    version = sys.argv[1]
    request = urllib.request.Request(
        f"https://api.github.com/repos/frida/frida/releases/tags/{version}",
        headers={"Accept": "application/vnd.github+json", "User-Agent": "CoreDeck"},
    )
    with open_release(request) as response:
        release = json.load(response)
    published = {
        asset["name"]: {
            "digest": asset.get("digest", ""),
            "url": asset.get("browser_download_url", ""),
        }
        for asset in release.get("assets", [])
    }

    devkit: dict[str, dict[str, str]] = {}
    server: dict[str, dict[str, str]] = {}
    missing = False
    for host in DEVKITS:
        name = f"frida-core-devkit-{version}-{host}.tar.xz"
        pin = pin_for(published, name)
        if pin is None:
            print(f"MISSING {name}", file=sys.stderr)
            missing = True
        else:
            devkit[host] = pin
            print(f"{name} {pin['sha256']}")
            print(f"  {pin['url']}")
    for abi in SERVERS:
        name = f"frida-server-{version}-{abi}.xz"
        pin = pin_for(published, name)
        if pin is None:
            print(f"MISSING {name}", file=sys.stderr)
            missing = True
        else:
            server[abi] = pin
            print(f"{name} {pin['sha256']}")
            print(f"  {pin['url']}")
    if missing:
        return 1

    stamp = datetime.now().astimezone().strftime("%Y-%m-%d %H:%M %z")
    text = (
        json.dumps(
            {
                "_comment": f"Generated by tools/update_frida_pins.py at {stamp}. Do not edit by hand.",
                "version": version,
                "devkit": devkit,
                "server": server,
            },
            indent=2,
        )
        + "\n"
    )
    temporary = PINS.with_suffix(".json.tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(PINS)
    print(f"Updated {PINS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
